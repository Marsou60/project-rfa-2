-- Abonnements Web Push de la PWA RFA.
--
-- PAS ENCORE APPLIQUÉ. Ne pas lancer ce script tant que Martial ne l'a pas
-- relu. Il ne touche qu'une table nouvelle, public.pwa_push_subscriptions.
-- Il ne modifie aucune table existante (notes_clients, nathalie_adherents,
-- contrats, pure data, etc.).
--
-- À lancer UNE FOIS, à la main, sur le projet Supabase du groupement :
--   Tableau de bord → SQL Editor → coller ce fichier → Run.
--
-- RLS : aucune policy. anon et authenticated n'ont aucun droit. Le backend
-- Railway (rôle postgres) contourne le RLS, comme pour adherent_positions.
-- L'API Supabase publique ne peut donc pas lire les clés d'abonnement.

CREATE TABLE IF NOT EXISTS public.pwa_push_subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    endpoint text NOT NULL UNIQUE,
    p256dh text NOT NULL,
    auth_secret text NOT NULL,
    user_agent text,
    created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.pwa_push_subscriptions IS
    'Abonnements Web Push des utilisateurs de la PWA. Clés privées du téléphone, pas des secrets VAPID.';

ALTER TABLE public.pwa_push_subscriptions ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.pwa_push_subscriptions FROM PUBLIC;
REVOKE ALL ON TABLE public.pwa_push_subscriptions FROM anon;
REVOKE ALL ON TABLE public.pwa_push_subscriptions FROM authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.pwa_push_subscriptions TO service_role;
